# написания, которые остаются после чистки текста и каноничными не являются.
# Применяются и к накопленным строкам целевых файлов, поэтому старые варианты
# исправляются на ближайшем прогоне.
STORE_ALIASES = {
    "Kazakhyuvelir MEGA - Астана": "Астана Mega Silk Way",
    "Kazakhyuvelir Esentai - Алматы": "Алматы Esentai Mall",
    # второй салон той же точки, отдельным магазином в модели не считается
    "Актау Салон 2": "Актау",
    # написание Esentai до переезда в Mall, встречалось в остатках
    "Алматы Esentai": "Алматы Esentai Mall",
}

_WHITESPACE_RE = re.compile(r"\s+")
_QUOTES = '"«»“”'
_SALON_PREFIX = "Ювелирный салон "
# 1С и предыдущие прогоны оставляют в колонке заглушки вместо пустого значения
_EMPTY_TOKENS = {"", "nan", "none", "null", "<na>", "-", "не указан"}


def collapse_spaces(value):
    """Схлопывает пробелы и неразрывные пробелы, заглушки приводит к NaN.

    Кавычки не трогает: ключи `CARD_GROUP_MAP` содержат их как есть, код
    сравнивается со справочником точно.
    """
    if value is None or pd.isna(value):
        return pd.NA

    text = _WHITESPACE_RE.sub(" ", str(value).replace("\xa0", " ")).strip()
    if text.lower() in _EMPTY_TOKENS:
        return pd.NA

    return text


def clean_store(value):
    """Чистит одно название: пробелы, префикс салона, кавычки, алиасы."""
    text = collapse_spaces(value)
    if pd.isna(text):
        return pd.NA

    text = text.replace(_SALON_PREFIX, "")
    for quote in _QUOTES:
        text = text.replace(quote, "")
    text = _WHITESPACE_RE.sub(" ", text).strip()
    if text.lower() in _EMPTY_TOKENS:
        return pd.NA

    return STORE_ALIASES.get(text, text)


def normalize_stores(values, logger=None, source=""):
    """Приводит колонку с названием магазина к каноническому виду.

    Для источников, где магазин приходит текстом. Незнакомое название
    остаётся как есть, но попадает в предупреждение.
    """
    result = values.map(clean_store)
    _warn_unknown(result, logger, source)
    return result


def map_store_codes(values, mapping, logger=None, source="", ignore=None):
    """Разворачивает код магазина (группа карты, склад) в название.

    Незнакомый код даёт пустой магазин и предупреждение. `ignore` — маска
    строк, о которых предупреждать не нужно (например, склады "ВС (...)",
    у которых магазина нет по определению).
    """
    cleaned = values.map(collapse_spaces)
    result = cleaned.map(mapping)

    unmapped = cleaned.notna() & result.isna()
    if ignore is not None:
        unmapped &= ~ignore
    if unmapped.any() and logger is not None:
        logger.warning(
            "%s: коды магазина не найдены в справочнике, магазин пуст: %s",
            source or "stores",
            sorted(cleaned[unmapped].unique()),
        )

    return result


def _warn_unknown(result, logger, source):
    unknown = result.notna() & ~result.isin(CANONICAL_STORES)
    if unknown.any() and logger is not None:
        logger.warning(
            "%s: магазины вне справочника, оставлены как есть: %s. "
            "Дополните lib/stores.py, если открылась новая точка.",
            source or "stores",
            sorted(result[unknown].unique()),
        )
