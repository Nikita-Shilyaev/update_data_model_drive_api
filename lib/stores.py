"""Единый справочник магазинов для всех целевых таблиц модели.

Названия магазинов приходят из источников в трёх разных видах:

* текстом с мусором — `Ювелирный салон "Алмаз"` (продажи, акции, рассрочка,
  оплата сертификатов): чистится `normalize_stores`;
* кодом группы карты — `01 г. Алматы "Алмаз"` (карты): `CARD_GROUP_MAP`;
* кодом склада — `1 (Алмаз-Алматы)` (остатки): `SKLAD_STORE_MAP`.

Эталон написания — значения `CARD_GROUP_MAP`, они же `CANONICAL_STORES`:
именно в этом виде магазин должен лежать в любой целевой таблице. Все три
пути приведения ведут в этот список, поэтому новая точка заводится здесь
один раз, а не в каждом скрипте отдельно.

Посещения (`update_visits.py`) сюда не входят: в гугл-таблице магазины уже
записаны в каноническом виде и не нуждаются в приведении.

Что делает функция с непонятным значением, зависит от того, был ли исходник
читаемым названием:

* `normalize_stores` (текстовые источники) оставляет незнакомое название как
  есть и пишет предупреждение — это уже читаемое имя, терять его хуже, чем
  довезти до целевого файла;
* `map_store_codes` (карты, остатки) оставляет магазин пустым и пишет
  предупреждение — сырому коду вида `23 г.Костанай «Рубин»` в целевом файле
  не место.

В обоих случаях предупреждение в логе — сигнал, что открылась новая точка и
словарь в этом модуле пора дополнить.
"""

